@dataclass
class Suggestion:
    crisis: bool = False
    message: str = ""
    patterns: list = field(default_factory=list)       # أسماء وشروحات
    evidence: list = field(default_factory=list)
    alternatives: list = field(default_factory=list)
    steps: list = field(default_factory=list)


def is_crisis(text: str) -> bool:
    t = normalize(text)
    return any(w in t for w in CRISIS_WORDS)


def _score(pattern: Pattern, t: str) -> int:
    return sum(pattern.weight for w in pattern.triggers if normalize(w) in t)


def _topic(t: str):
    for name, (words, steps) in TOPICS.items():
        if any(normalize(w) in t for w in words):
            return name, steps
    return None, []


def suggest(thought: str, max_patterns: int = 2) -> Suggestion:
    """يرجع اقتراحات للفكرة. فكرة فاضية ترجع اقتراح عام."""
    t = normalize(thought)
    if is_crisis(thought):
        return Suggestion(crisis=True, message=CRISIS_MESSAGE)
    scored = sorted(((_score(p, t), p) for p in PATTERNS), key=lambda x: -x[0])
    chosen = [p for s, p in scored if s > 0][:max_patterns] or [GENERIC]
    out = Suggestion()
    for p in chosen:
        out.patterns.append((p.title, p.explain))
        for src, dst in ((p.evidence, out.evidence), (p.alternatives, out.alternatives)):
            for item in src[:2] if len(chosen) > 1 else src:
                if item not in dst:
                    dst.append(item)
    _, topic_steps = _topic(t)
    steps = list(topic_steps[:2])
    for p in chosen:
        for s in p.steps:
            if s not in steps and len(steps) < 4:
                steps.append(s)
    out.steps = steps[:4]
    return out
